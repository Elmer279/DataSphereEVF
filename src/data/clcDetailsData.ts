/**
 * Normalizes CLC names for resilient matching across spelling and naming variations
 * Handles "Community Based Learning Center", "School Based Learning Center", "Community Learning Center", "CBLC", "SBLC", etc.
 */
export function normalizeClcName(name: string): string {
  return (name || '')
    .toLowerCase()
    .replace(/community[- ]based learning center/gi, '')
    .replace(/school[- ]based learning center/gi, '')
    .replace(/community learning center/gi, '')
    .replace(/learning center/gi, '')
    .replace(/community[- ]based/gi, '')
    .replace(/school[- ]based/gi, '')
    .replace(/cblc|sblc|clc/gi, '')
    .replace(/memorial library/gi, '')
    .replace(/santo/gi, 'sto')
    .replace(/barangay/gi, '')
    .replace(/brgy\.?/gi, '')
    .replace(/sitio/gi, '')
    .replace(/elementary school/gi, '')
    .replace(/integrated school/gi, '')
    .replace(/high school/gi, '')
    .replace(/center/gi, '')
    .replace(/community/gi, '')
    .replace(/[^a-z0-9]/gi, '')
    .trim();
}

/**
 * Safely compares two CLC names, ensuring Roman numerals and numeric suffixes
 * (e.g. "Cut-Cut I" vs "Cut-Cut II", "Balibago I" vs "Balibago II") do not produce false substring matches.
 */
export function isClcNameMatch(target: string, candidate: string): boolean {
  if (!target || !candidate) return false;
  const tTrim = target.trim().toLowerCase();
  const cTrim = candidate.trim().toLowerCase();
  if (tTrim === cTrim) return true;

  const normTarget = normalizeClcName(target);
  const normCand = normalizeClcName(candidate);
  if (!normTarget || !normCand) return false;
  if (normTarget === normCand) return true;

  // Extract trailing Roman numerals (I, II, III, IV, V) or numeric digits (1, 2)
  const getSuffix = (s: string) => {
    const m = s.match(/(?:i{1,3}|iv|v|\d+)$/i);
    return m ? m[0].toLowerCase() : '';
  };
  const targetSuffix = getSuffix(normTarget);
  const candSuffix = getSuffix(normCand);

  // If one has a distinct numeric/Roman suffix and the other has a different one, they CANNOT match
  if (targetSuffix && candSuffix && targetSuffix !== candSuffix) {
    return false;
  }
  // If one has a suffix (e.g. "cutcuti" -> "i") but the other has none, or vice versa, they CANNOT match
  if (Boolean(targetSuffix) !== Boolean(candSuffix)) {
    return false;
  }

  // Safe substring match only when stems match without conflicting suffixes
  return (
    (normTarget.length >= 4 && normCand.includes(normTarget)) ||
    (normCand.length >= 4 && normTarget.includes(normCand))
  );
}

/**
 * Returns the District for a given CLC name.
 */
export function getOfficialDistrictForCLC(clcName: string): string | undefined {
  if (!clcName) return undefined;
  const trimmed = clcName.trim().toLowerCase();
  if (trimmed.includes('sebastian')) return 'Central A';
  
  // 1. Exact match
  const exact = OFFICIAL_CLC_DETAILS_LIST.find(
    item => item.clcName.trim().toLowerCase() === trimmed
  );
  if (exact && exact.district && exact.district.toLowerCase() !== 'central') return exact.district;

  // 2. Substring match
  const sub = OFFICIAL_CLC_DETAILS_LIST.find(
    item => (trimmed.includes(item.clcName.trim().toLowerCase()) || item.clcName.trim().toLowerCase().includes(trimmed)) &&
      item.district && item.district.toLowerCase() !== 'central'
  );
  if (sub && sub.district) return sub.district;

  // 3. Normalized stem match with suffix safety
  const normMatch = OFFICIAL_CLC_DETAILS_LIST.find(
    item => isClcNameMatch(clcName, item.clcName) &&
      item.district && item.district.toLowerCase() !== 'central'
  );
  if (normMatch && normMatch.district) return normMatch.district;

  return undefined;
}

/**
 * Returns the primary District for a given teacher name based on their assigned CLCs.
 */
export function getOfficialDistrictForTeacher(teacherName: string): string | undefined {
  if (!teacherName) return undefined;
  const normalized = teacherName.trim().toUpperCase().replace(/Ň|Ñ/g, 'N');
  const matches = OFFICIAL_CLC_DETAILS_LIST.filter(item => {
    if (!item.teacherName) return false;
    const itemNorm = item.teacherName.trim().toUpperCase().replace(/Ň|Ñ/g, 'N');
    return (itemNorm === normalized || item.teacherName.trim().toUpperCase() === teacherName.trim().toUpperCase()) &&
      item.district && item.district.toLowerCase() !== 'central';
  });

  if (matches.length > 0) {
    const counts: Record<string, number> = {};
    matches.forEach(m => {
      if (m.district) {
        counts[m.district] = (counts[m.district] || 0) + 1;
      }
    });
    const sorted = Object.entries(counts).sort((a, b) => b[1] - a[1]);
    if (sorted.length > 0) return sorted[0][0];
  }

  return undefined;
}


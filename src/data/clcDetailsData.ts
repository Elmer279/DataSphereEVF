/**
 * Resolves the PSDS name and district designation based on the selected district filter.
 * References live Learning Center Details if available with fallback to the official PSDS map.
 */
export function getPsdsForDistrict(
  selectedDistrict: string,
  clcList?: CLCDetailItem[]
): { psdsName: string; districtDesignation: string; districtName: string } {
  if (!selectedDistrict || selectedDistrict.toLowerCase() === 'all') {
    return {
      psdsName: 'Rene B. Miclat, PhD',
      districtDesignation: 'PSDS, Division ALS Focal Person',
      districtName: 'All Districts'
    };
  }

  const normalized = selectedDistrict.trim().toLowerCase();
  
  // Find case-insensitive canonical district key
  const canonicalDistrict = Object.keys(OFFICIAL_DISTRICT_PSDS_MAP).find(
    d => d.trim().toLowerCase() === normalized
  ) || selectedDistrict;

  // Check if live CLC data has a psdsSupervisor
  let psdsName: string | undefined;
  if (clcList && clcList.length > 0) {
    const clcMatch = clcList.find(
      c => (c.district || '').trim().toLowerCase() === normalized && c.psdsSupervisor
    );
    if (clcMatch?.psdsSupervisor) {
      psdsName = clcMatch.psdsSupervisor;
    }
  }

  if (!psdsName) {
    psdsName = OFFICIAL_DISTRICT_PSDS_MAP[canonicalDistrict] || 'Rene B. Miclat, PhD';
  }

  return {
    psdsName,
    districtDesignation: `PSDS, ${canonicalDistrict}`,
    districtName: canonicalDistrict
  };
}

export const OVERALL_TOTAL_MAPPED_LITERACY: number = 5420;

export function getBarangayMappedCount(bName: string): number {
  if (!bName) return 0;
  const clean = (s: string) => s.toLowerCase()
    .replace(/^barangay\s+/i, '')
    .replace(/^brgy\.?\s+/i, '')
    .replace(/\bsto\.?\b/g, 'santo')
    .replace(/\bsta\.?\b/g, 'santa')
    .replace(/[^a-z0-9]/g, '');

  const target = clean(bName);
  for (const [key, val] of Object.entries(LITERACY_MAPPING_COUNTS)) {
    if (clean(key) === target) return val.totalMapped;
  }
  for (const [key, val] of Object.entries(LITERACY_MAPPING_COUNTS)) {
    if (clean(key).includes(target) || target.includes(clean(key))) return val.totalMapped;
  }
  return 0;
}
